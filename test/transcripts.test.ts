function fixture() {
  const home = fs.mkdtempSync(path.join(os.homedir(), "tx-"));
  const claude = path.join(home, "claude");
  const codex = path.join(home, "codex");
  fs.mkdirSync(path.join(claude, "-Users-me-Code-app"), { recursive: true });
  fs.mkdirSync(path.join(codex, "2026", "09", "02"), { recursive: true });
  const cFile = path.join(claude, "-Users-me-Code-app", "c1.jsonl");
  const xId = "019f8f72-e895-7130-844d-ec86750ff888";
  const xFile = path.join(codex, "2026", "09", "02", `rollout-2026-09-02T09-00-00-${xId}.jsonl`);
  fs.writeFileSync(cFile, claudeLines("c1").join("\n") + "\n");
  fs.writeFileSync(xFile, codexLines(xId).join("\n") + "\n");
  const idx = new TranscriptIndex(path.join(home, "index.db"), { claude, codex }, 2);
  return { home, idx, cFile, xFile, xId };
}

describe("reading transcripts", () => {
  it("takes what was said and which files and commands a Claude session touched — not tool output or noise", () => {
    const parsed = claudeLines("c1").map((l) => parseClaudeLine(l, "c1"));
    const texts = parsed.flatMap((p) => p.chunks.map((c) => `${c.kind}:${c.text}`));
    expect(texts).toEqual(["message:Why is the donor export so slow?", "message:Looking at the query builder first.", "tool:Read /Users/me/Code/app/server/exportQuery.ts"]);
    expect(parsed.at(-1)!.conv!.title).toBe("Speed up the donor export");
    expect(parsed[4].usage).toMatchObject({ id: "msg_1", input: 10, output: 20, cacheRead: 300, cacheWrite: 40 });
  });
  it("reads Codex rollouts: the session's folder, messages, commands and patched files", () => {
    const parsed = codexLines("x1").map((l) => parseCodexLine(l, "x1"));
    expect(parsed[0].conv).toMatchObject({ id: "x1", cwd: "/Users/me/Code/etl" });
    expect(parsed[1].conv!.model).toBe("gpt-6-astra");
    expect(parsed.flatMap((p) => p.chunks.map((c) => c.text))).toEqual([
      "Add a retry to the nightly ETL",
      "exec_command rg nightlyJob src",
      "apply_patch src/jobs/nightly.py",
      "Added exponential backoff.",
    ]);
  });
  it("skips lines that aren't JSON", () => {
    expect(parseClaudeLine("{oops", "c").chunks).toEqual([]);
    expect(parseCodexLine("", "x").chunks).toEqual([]);
  });
});

describe("searching", () => {
  it("turns free text into a safe query: every word, the last as a prefix", () => {
    expect(ftsQuery("donor export")).toBe('"donor" "export"*');
    expect(ftsQuery('auth "middleware OR NEAR(')).toBe('"auth" "middleware" "OR" "NEAR"*');
    expect(ftsQuery("src/jobs/nightly.py")).toBe('"src/jobs/nightly.py"*');
    expect(ftsQuery("  ")).toBeNull();
  });

  it("finds Claude and Codex conversations by words, files and commands, best passage marked", async () => {
    const { idx, xId } = fixture();
    await idx.sync();
    expect(idx.stats()).toEqual({ conversations: 2, files: 2 });
    const [donor] = idx.search("donor expo");
    expect(donor).toMatchObject({ id: "c1", agent: "claude", cwd: "/Users/me/Code/app", title: "Speed up the donor export", model: "claude-opus-5-5" });
    expect(donor.snippet).toContain("\u0001donor\u0002");
    expect(idx.search("exportQuery")[0]).toMatchObject({ id: "c1", kind: "tool" });
    expect(idx.search("nightly.py")[0]).toMatchObject({ id: xId, agent: "codex", cwd: "/Users/me/Code/etl", title: "Add a retry to the nightly ETL" });
    expect(idx.search("zebra")).toEqual([]); // tool output isn't indexed
    expect(idx.search('" OR (')).toEqual([]); // odd input never throws
  });

  it("reads only what was appended, leaves a half-written line for later, and re-reads a replaced file", async () => {
    const { idx, cFile } = fixture();
    await idx.sync();
    const line = (text: string, at: string) => L({ type: "user", sessionId: "c1", timestamp: at, message: { role: "user", content: text } });
    fs.appendFileSync(cFile, line("now add pagination", "2026-09-01T11:00:00Z") + "\n" + line("half written", "2026-09-01T11:05:00Z").slice(0, 30));
    await idx.sync();
    expect(idx.search("pagination")).toHaveLength(1);
    expect(idx.search("half")).toEqual([]);
    fs.appendFileSync(cFile, line("half written", "2026-09-01T11:05:00Z").slice(30) + "\n");
    await idx.sync();
    expect(idx.search("half written")).toHaveLength(1);
    expect(idx.search("donor")).toHaveLength(1); // nothing read twice
    fs.writeFileSync(cFile, line("a fresh start", "2026-09-03T08:00:00Z") + "\n");
    await idx.sync();
    expect(idx.search("donor")).toEqual([]);
    expect(idx.search("fresh start")).toHaveLength(1);
  });

  it("folds a sync requested mid-pass into one more pass", async () => {
    const { idx } = fixture();
    const a = idx.sync();
    const b = idx.sync();
    expect(b).toBe(a);
    await a;
    expect(idx.indexing).toBe(false);
    expect(idx.stats().conversations).toBe(2);
  });
});

describe("opening a hit", () => {
  const hit = (id: string) => ({ id, agent: "claude" as const, cwd: "/c", title: "t", started: 0, updated: 0, model: null, snippet: "", at: 0, kind: "message" as const });
  const session = (id: string, conv: string) => ({ id, conversation: { agent: "claude", id: conv } }) as unknown as SessionInfo;
  it("goes to the open pane, else restores the closed session, else the Collaborate room, else resumes it", () => {
    const room = { id: "r1", title: "Perf room", participants: [{ key: "opus", conversationId: "c-room", lookupConversationId: "c-lookup" }] } as unknown as CollabRoom;
    const linked = linkHits([hit("c-live"), hit("c-closed"), hit("c-room"), hit("c-lookup"), hit("c-other")], [session("s1", "c-live")], [session("s2", "c-closed")], [room]);
    expect(linked.map((h) => h.open)).toEqual([
      { how: "pane", sessionId: "s1" },
      { how: "previous", sessionId: "s2" },
      { how: "room", roomId: "r1", roomTitle: "Perf room" },
      { how: "room", roomId: "r1", roomTitle: "Perf room" },
      { how: "resume" },
    ]);
  });
});
